def verdict(r):
    over5,thr,long_all,hes,silent=r['over5'],r['thr'],r['long_all'],r['hes'],r['silent']
    t=r['teacher']; gap=thr-over5
    # lesson4逻辑:意图×信号交叉
    if hes>=6: return '🟡卡壳型(该等+提示)'
    if t=='该等':
        if over5>=thr or long_all>=45: return '🟢该等(意图+数据)'
        return '🟢该等(意图强)'
